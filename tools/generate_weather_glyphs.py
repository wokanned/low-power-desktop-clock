"""Generate the fixed 16x16 Chinese glyphs used by the weather page."""

import argparse
from pathlib import Path

from PIL import Image, ImageChops, ImageDraw, ImageFont


ROOT = Path(__file__).resolve().parents[1]
FONT_CODEPOINTS = (
    0x6DF1, 0x5733, 0x6E5B, 0x6C5F, 0x5DF2, 0x8FC7, 0x671F,
    0x7B49, 0x5F85, 0x5929, 0x6C14, 0x6570, 0x636E, 0x672A, 0x77E5,
    0x6674, 0x591A, 0x4E91, 0x9634, 0x5C0F, 0x96E8, 0x4E2D, 0x5927,
    0x96F7, 0x9635, 0x96EA, 0x5939, 0x96FE, 0x973E, 0x5F53, 0x524D,
    0x6700, 0x9AD8, 0x4F4E, 0x6E29, 0x6E7F, 0x5EA6, 0x98CE, 0x5411, 0x901F,
    0x6765, 0x6E90, 0x66F4, 0x65B0, 0x65F6, 0x95F4, 0x4E1C, 0x5317,
    0x5357, 0x897F, 0x9759,
)
CELL_SIZE = 16


def glyph_bitmap(font, char):
    left, top, right, bottom = font.getbbox(char)
    image = Image.new("L", (right - left, bottom - top), 255)
    ImageDraw.Draw(image).text((-left, -top), char, font=font, fill=0)
    ink = ImageChops.invert(image).getbbox()
    if ink is None:
        raise ValueError(f"Empty weather glyph: U+{ord(char):04X}")
    image = image.crop(ink).resize((CELL_SIZE, CELL_SIZE), Image.Resampling.LANCZOS)
    image = image.point([1 if value < 128 else 0 for value in range(256)])
    packed = bytearray()
    for y in range(CELL_SIZE):
        for x in range(0, CELL_SIZE, 8):
            value = 0
            for bit in range(8):
                if image.getpixel((x + bit, y)) != 0:
                    value |= 1 << (7 - bit)
            packed.append(value)
    return packed


def generate(font_path):
    font = ImageFont.truetype(str(font_path), 18)
    codepoints = sorted(set(FONT_CODEPOINTS))
    rows = []
    for codepoint in codepoints:
        bitmap = glyph_bitmap(font, chr(codepoint))
        values = ", ".join(f"0x{value:02X}U" for value in bitmap)
        rows.append(f"    {{0x{codepoint:04X}U, {{{values}}}}}")
    header = """/* Generated by tools/generate_weather_glyphs.py; do not edit by hand. */
#ifndef WEATHER_GLYPHS_H
#define WEATHER_GLYPHS_H
#include <stdint.h>
typedef struct {
    uint16_t codepoint;
    uint8_t bitmap[32];
} weather_glyph_t;
extern const weather_glyph_t g_weather_glyphs[];
extern const uint8_t g_weather_glyph_count;
#endif
"""
    source = """/* Generated offline; 16x16, row-major, MSB first, 1=black. */
#include \"weather_glyphs.h\"

const weather_glyph_t g_weather_glyphs[] = {
""" + ",\n".join(rows) + "\n};\n"
    source += f"const uint8_t g_weather_glyph_count = {len(codepoints)}U;\n"
    return header, source


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, default=Path("C:/Windows/Fonts/msyh.ttc"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    header, source = generate(args.font)
    for name, content in (("weather_glyphs.h", header), ("weather_glyphs.c", source)):
        path = ROOT / "resources" / name
        if args.check:
            if not path.exists() or path.read_text(encoding="ascii") != content:
                raise SystemExit(f"Generated resource differs: {path}")
        else:
            path.write_text(content, encoding="ascii", newline="\n")
    print("Weather glyphs: generated" if not args.check else "Weather glyphs: verified")


if __name__ == "__main__":
    main()
