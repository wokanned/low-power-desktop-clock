"""Generate licensed 1-bit weather page fonts (no device IO).

Terminus originals live in resources/weather_fonts under SIL OFL 1.1.
Large/medium numeric glyphs use Cascadia Mono's embedding license. Only the
derived bitmaps and the exact embedded license are distributed, not the TTF.
The source defaults to the Windows-installed font, or pass --numeric-font.
"""
import argparse
import hashlib
import struct
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT_DIR = ROOT / "resources/weather_fonts"
SPECS = (("small", "ter-u14n.bdf"), ("normal", "ter-u16n.bdf"),
         ("bold", "ter-u20b.bdf"), ("medium", "ter-u24b.bdf"),
         ("large", "ter-u32b.bdf"))
CODES = list(range(32, 127)) + [176]


def bdf(path):
    lines = path.read_text(encoding="ascii").splitlines()
    glyphs = {}
    for index, line in enumerate(lines):
        if line.startswith("ENCODING "):
            code = int(line.split()[1])
            end = lines.index("ENDCHAR", index)
            bitmap = lines.index("BITMAP", index, end)
            width, height, _, _ = map(int, next(v for v in lines[index:end] if v.startswith("BBX ")).split()[1:])
            values = lines[bitmap + 1:end]
            glyphs[code] = (width, height, bytes.fromhex("".join(values)))
    return glyphs


def pack(image):
    width, height = image.size
    values = bytearray((width * height + 7) // 8)
    for y in range(height):
        for x in range(width):
            if image.getpixel((x, y)):
                bit = y * width + x
                values[bit // 8] |= 0x80 >> (bit % 8)
    return bytes(values)


def extract_license(path):
    data = path.read_bytes()
    count = struct.unpack_from(">H", data, 4)[0]
    for index in range(count):
        entry = 12 + index * 16
        if data[entry:entry + 4] == b"name":
            offset = struct.unpack_from(">I", data, entry + 8)[0]
            break
    _, count, storage = struct.unpack_from(">HHH", data, offset)
    selected = {}
    for index in range(count):
        platform, _, _, name, length, relative = struct.unpack_from(">HHHHHH", data, offset + 6 + index * 12)
        if name in (0, 13, 14) and name not in selected:
            value = data[offset + storage + relative:offset + storage + relative + length]
            selected[name] = value.decode("utf-16-be" if platform in (0, 3) else "latin-1")
    return "\n\n".join(selected[key] for key in sorted(selected)) + "\n"


def generate(numeric_font):
    header = """/* Generated by tools/generate_weather_pages_assets.py. */
#ifndef WEATHER_PAGES_ASSETS_H
#define WEATHER_PAGES_ASSETS_H
#include <stdint.h>
typedef struct {
    uint32_t offset;
    uint8_t width, height, advance;
    int8_t top;
} weather_page_glyph_t;
typedef struct {
    const weather_page_glyph_t *p_glyphs;
    const uint8_t *p_bits;
    uint8_t height;
} weather_page_font_t;
"""
    output = ["/* Generated bitmap derivatives; licenses in resources/weather_fonts/. */",
              '#include "weather_pages_assets.h"']
    for name, filename in SPECS + (("number", None), ("temperature", None)):
        glyphs, bits = [], bytearray()
        if filename:
            original = bdf(FONT_DIR / filename)
            width, height, _ = original[32]
            # Crop a shared vertical span so all characters have the same baseline.
            images = {}
            for code in CODES:
                w, h, raw = original[code]
                images[code] = Image.frombytes("1", (w, h), raw)
            boxes = [image.getbbox() for image in images.values() if image.getbbox()]
            top, bottom = min(box[1] for box in boxes), max(box[3] for box in boxes)
            target_height = bottom - top
            for code in CODES:
                image = images[code].crop((0, top, width, bottom))
                raw = pack(image)
                glyphs.append((len(bits), width, target_height, width, 0))
                bits.extend(raw)
        else:
            size = 24 if name == "number" else 54
            face = ImageFont.truetype(str(numeric_font), size)
            target_height = face.getbbox("0123456789")[3] - face.getbbox("0123456789")[1]
            baseline = face.getbbox("0123456789")[1]
            for code in CODES:
                char = chr(code) if chr(code) in "0123456789.-+~?:" else " "
                box = face.getbbox(char)
                image = Image.new("1", (box[2] - box[0] + 4, size + 8), 0)
                draw = ImageDraw.Draw(image)
                draw.fontmode = "1"
                draw.text((2 - box[0], -baseline), char, font=face, fill=1)
                ink = image.getbbox()
                if ink:
                    image = image.crop(ink)
                    raw = pack(image)
                    advance = image.width + (2 if name == "number" else 3)
                    glyphs.append((len(bits), image.width, image.height, advance, ink[1]))
                    bits.extend(raw)
                else:
                    glyphs.append((len(bits), 0, 0, size // 3, 0))
        output.append(f"static const uint8_t s_{name}_bits[] = {{")
        for index in range(0, len(bits), 16):
            output.append("    " + ", ".join(f"0x{value:02X}U" for value in bits[index:index + 16]) + ",")
        output.append("};")
        output.append(f"static const weather_page_glyph_t s_{name}_glyphs[] = {{")
        output.extend("    {%dU, %dU, %dU, %dU, %d}," % glyph for glyph in glyphs)
        output.append("};")
        output.append(f"const weather_page_font_t g_weather_page_{name} = {{s_{name}_glyphs, s_{name}_bits, {target_height}U}};")
        header += f"extern const weather_page_font_t g_weather_page_{name};\n"
    header += "#endif\n"
    (ROOT / "resources/weather_pages_assets.h").write_text(header, encoding="ascii")
    (ROOT / "resources/weather_pages_assets.c").write_text("\n".join(output) + "\n", encoding="ascii")
    license_text = extract_license(numeric_font)
    if "Permission is hereby granted, free of charge" not in license_text:
        raise ValueError("Numeric source does not carry the expected redistribution license")
    (FONT_DIR / "cascadia-license.txt").write_text(license_text, encoding="utf-8")
    (FONT_DIR / "numeric-source.txt").write_text(
        "Source: Microsoft Cascadia Mono (Windows-installed CascadiaMono.ttf)\n"
        f"SHA256: {hashlib.sha256(numeric_font.read_bytes()).hexdigest()}\n"
        "Generated derivative family name: DeskClock Weather Numbers\n"
        "Only derived 1-bit glyph arrays are distributed; the TTF is not copied.\n"
        "Numeric source can be selected explicitly with --numeric-font.\n", encoding="ascii")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--numeric-font", type=Path, default=Path("C:/Windows/Fonts/CascadiaMono.ttf"))
    args = parser.parse_args()
    generate(args.numeric_font)
