"""Build the clock's offline 2bpp glyphs and pixel icons (Pillow required).

The firmware only consumes the generated C arrays. Bahnschrift is read from
Windows locally; the font file is never copied into the repository.
"""

import argparse
import hashlib
import math
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


ROOT = Path(__file__).resolve().parents[1]
SCALE = 4
FONT_SPECS = (
    ("MAIN", 76, 75, "0123456789:-"),
    ("DATE", 18, 95, "0123456789-/ AMONTEUWDFRISH"),
    ("LABEL", 12, 100, "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ /+-:"),
    ("VALUE", 24, 90, "0123456789N/A%Ch.-+"),
    ("WIFI", 17, 100, "0123456789h ago+"),
    ("ERROR", 14, 85, "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ /+-:"),
    ("HEADER_TIME", 22, 80, "0123456789:-"),
    ("HEADER_DATE", 16, 85, "0123456789-/ AMONTEUWDFRISH"),
)
PIXEL_ALIGNED_FONTS = {"DATE", "LABEL", "VALUE", "WIFI"}


def quantize(image):
    return image.point([3 - min(3, (value + 42) // 85) for value in range(256)])


def pack(image):
    width, height = image.size
    data = bytearray()
    for y in range(height):
        for x in range(0, width, 4):
            value = 0
            for lane in range(4):
                if x + lane < width:
                    value |= image.getpixel((x + lane, y)) << (6 - 2 * lane)
            data.append(value)
    return data


def icon(name):
    size = 14 if name == "circle" else 16 if name == "moon" else 18
    icon_scale = SCALE if name == "moon" else 1
    image = Image.new("L", (size * icon_scale, size * icon_scale), 255)
    draw = ImageDraw.Draw(image)

    def box(values):
        return tuple(round(value * icon_scale) for value in values)

    if name == "battery":
        draw.rectangle(box((1, 5, 14, 13)), outline=0, width=icon_scale)
        draw.rectangle(box((15, 7, 16, 11)), fill=0)
    elif name == "circle":
        draw.ellipse(box((1, 1, 12, 12)), outline=0, width=1)
    elif name == "wifi":
        draw.arc(box((1, 4, 17, 20)), 225, 315, fill=0, width=1)
        draw.arc(box((4, 8, 14, 18)), 225, 315, fill=0, width=1)
        draw.ellipse(box((8, 13, 10, 15)), fill=0)
    elif name == "thermometer":
        draw.rounded_rectangle(box((7, 2, 10, 12)), radius=icon_scale,
                               outline=0, width=icon_scale)
        draw.ellipse(box((5, 9, 12, 16)), fill=255, outline=0, width=icon_scale)
        draw.line(box((8.5, 5, 8.5, 13)), fill=0, width=icon_scale)
        draw.ellipse(box((7, 11, 10, 14)), fill=0)
    elif name == "moon":
        draw.ellipse(box((2, 2, 13, 13)), fill=0)
        draw.ellipse(box((6, 0, 17, 11)), fill=255)
    if icon_scale == 1:
        return image.point([3 if value < 128 else 0 for value in range(256)])
    return quantize(image.resize((size, size), Image.Resampling.LANCZOS))


def c_bytes(name, values):
    rows = ["    " + ", ".join(f"0x{value:02X}U" for value in values[index:index + 16])
            for index in range(0, len(values), 16)]
    return f"static const uint8_t {name}[] = {{\n" + ",\n".join(rows) + "\n};\n"


def generate(font_path):
    header = """/* Generated by tools/generate_clock_assets.py; do not edit by hand. */
#ifndef CLOCK_GRAY_ASSETS_H
#define CLOCK_GRAY_ASSETS_H
#include <stdint.h>
typedef struct {
    uint32_t offset;
    uint8_t code, width, height, advance;
    int8_t y_offset;
} clock_gray_glyph_t;
typedef struct {
    const uint8_t *p_data;
    const clock_gray_glyph_t *p_glyphs;
    uint8_t count;
} clock_gray_font_t;
typedef struct {
    const uint8_t *p_data;
    uint8_t width, height;
} clock_gray_icon_t;
typedef enum {
"""
    header += "\n".join(f"    CLOCK_FONT_{spec[0]}," for spec in FONT_SPECS)
    header += "\n    CLOCK_FONT_COUNT\n} clock_gray_font_id_t;\n"
    names = ("battery", "circle", "wifi", "thermometer", "moon")
    header += "typedef enum {\n"
    header += "\n".join(f"    CLOCK_ICON_{name.upper()}," for name in names)
    header += "\n    CLOCK_ICON_COUNT\n} clock_gray_icon_id_t;\n"
    header += "extern const clock_gray_font_t g_clock_gray_fonts[CLOCK_FONT_COUNT];\n"
    header += "extern const clock_gray_icon_t g_clock_gray_icons[CLOCK_ICON_COUNT];\n#endif\n"
    source = '/* Generated offline; 0=white, 3=black, MSB pair first. */\n'
    source += f'/* Font SHA256: {hashlib.sha256(font_path.read_bytes()).hexdigest()} */\n'
    source += '#include "clock_gray_assets.h"\n\n'
    total = 0
    for name, size, width, charset in FONT_SPECS:
        pixel_aligned = name in PIXEL_ALIGNED_FONTS
        tabular = name == "MAIN"
        font_scale = 1 if pixel_aligned or tabular else SCALE
        font = ImageFont.truetype(str(font_path), size * font_scale)
        font.set_variation_by_axes([700 if pixel_aligned else 650 if tabular else 600, width])
        reference_top = font.getbbox("0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ")[1]
        glyphs = []
        data = bytearray()
        for char in sorted(set(charset)):
            left, top, right, bottom = font.getbbox(char)
            pixel_width = math.ceil((right - left) / font_scale)
            pixel_height = math.ceil((bottom - top) / font_scale)
            advance = round(font.getlength(char) / font_scale)
            y_offset = round((top - reference_top) / font_scale)
            if char == " ":
                pixel_width = pixel_height = 0
            else:
                image = Image.new("L", (pixel_width * font_scale,
                                        pixel_height * font_scale), 255)
                ImageDraw.Draw(image).text((-left, -top), char, font=font, fill=0)
                if pixel_aligned:
                    # Native-size hinting keeps small strokes on full black pixels.
                    image = image.point([3 if value < 128 else 0 for value in range(256)])
                    ink = image.getbbox()
                    if ink is None:
                        raise ValueError(f"Empty glyph: {name} {char!r}")
                    image = image.crop(ink)
                    pixel_width, pixel_height = image.size
                    y_offset += ink[1]
                    advance = max(advance, pixel_width + 1)
                elif tabular:
                    # Crop bearings, then center ink in fixed cells so minutes never move.
                    image = quantize(image)
                    ink = image.getbbox()
                    if ink is None:
                        raise ValueError(f"Empty glyph: {name} {char!r}")
                    image = image.crop(ink)
                    y_offset += ink[1]
                    cell_width = 12 if char == ":" else 34
                    if image.width > cell_width - 2:
                        raise ValueError(f"Main glyph has no cell padding: {char!r}")
                    cell = Image.new("L", (cell_width, image.height), 0)
                    cell.paste(image, ((cell_width - image.width) // 2, 0))
                    image = cell
                    pixel_width, pixel_height = image.size
                    advance = cell_width
                else:
                    image = image.resize((pixel_width, pixel_height),
                                         Image.Resampling.LANCZOS)
                    image = quantize(image)
                packed = pack(image)
                data.extend(packed)
            length = ((pixel_width + 3) // 4) * pixel_height
            glyphs.append((len(data) - length, ord(char), pixel_width, pixel_height,
                           advance, y_offset))
        total += len(data)
        source += c_bytes(f"s_font_{name.lower()}_data", data)
        source += f"static const clock_gray_glyph_t s_font_{name.lower()}_glyphs[] = {{\n"
        source += ",\n".join("    {%dU, %dU, %dU, %dU, %dU, %d}" % row for row in glyphs)
        source += "\n};\n\n"
    source += "const clock_gray_font_t g_clock_gray_fonts[CLOCK_FONT_COUNT] = {\n"
    source += ",\n".join(f"    {{s_font_{name.lower()}_data, s_font_{name.lower()}_glyphs, "
                           f"{len(set(charset))}U}}" for name, _, _, charset in FONT_SPECS)
    source += "\n};\n\n"
    for name in names:
        data = pack(icon(name))
        total += len(data)
        source += c_bytes(f"s_icon_{name}", data) + "\n"
    source += "const clock_gray_icon_t g_clock_gray_icons[CLOCK_ICON_COUNT] = {\n"
    source += ",\n".join(f"    {{s_icon_{name}, {icon(name).width}U, {icon(name).height}U}}"
                           for name in names)
    source += "\n};\n"
    return header, source, total


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, default=Path("C:/Windows/Fonts/bahnschrift.ttf"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    header, source, total = generate(args.font)
    for name, content in (("clock_gray_assets.h", header), ("clock_gray_assets.c", source)):
        path = ROOT / "resources" / name
        if args.check:
            if not path.exists() or path.read_text(encoding="ascii") != content:
                raise SystemExit(f"Generated resource differs: {path}")
        else:
            path.write_text(content, encoding="ascii", newline="\n")
    print(f"Clock resources: {total} bitmap bytes; " + ("verified" if args.check else "generated"))


if __name__ == "__main__":
    main()
